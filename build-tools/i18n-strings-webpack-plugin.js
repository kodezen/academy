/**
 * Records which translatable strings each entry bundle uses.
 *
 * WordPress only finds a script's JSON translations when the file is named
 * after the md5 of the *built* script path. Translation tools key their JSON
 * by the source files the .po references instead, and our bundle names carry
 * the plugin version, so those files never match. Academy\ScriptTranslations
 * falls back to the plugin's loaded .mo file, and this manifest tells it
 * which strings belong to each bundle so it does not have to inline the
 * whole catalogue.
 *
 * For every entry it writes `[entry file].i18n.php` next to the bundle
 * (e.g. frontendCurriculums.4.0.1.i18n.php), returning
 * `array( domain => array( msgid | array( msgid, context ), … ) )`.
 *
 * Strings are read from the final bundle (entry chunks plus the async chunks
 * they load) the same way `wp i18n make-pot` does: calls to __, _x, _n and
 * _nx, whether called directly, as `x.__()` or as webpack's `(0, x.__)()`,
 * with string-literal arguments.
 */
const acorn = require( 'acorn' );
const { Compilation, sources } = require( 'webpack' );

const PLUGIN_NAME = 'AcademyI18nStringsPlugin';

// Index of the context and domain arguments for each function.
const FUNCTIONS = {
	__: { context: null, domain: 1 },
	_x: { context: 1, domain: 2 },
	_n: { context: null, domain: 3 },
	_nx: { context: 3, domain: 4 },
};

function calleeName( callee ) {
	if ( callee.type === 'SequenceExpression' ) {
		return calleeName( callee.expressions[ callee.expressions.length - 1 ] );
	}
	if ( callee.type === 'Identifier' ) {
		return callee.name;
	}
	if ( callee.type === 'MemberExpression' ) {
		if ( ! callee.computed && callee.property.type === 'Identifier' ) {
			return callee.property.name;
		}
		if ( callee.computed && callee.property.type === 'Literal' ) {
			return callee.property.value;
		}
	}
	return null;
}

function stringValue( node ) {
	if ( ! node ) {
		return null;
	}
	if ( node.type === 'Literal' && typeof node.value === 'string' ) {
		return node.value;
	}
	if ( node.type === 'TemplateLiteral' && node.expressions.length === 0 ) {
		return node.quasis[ 0 ].value.cooked;
	}
	return null;
}

function walk( node, visit ) {
	if ( ! node || typeof node.type !== 'string' ) {
		return;
	}
	visit( node );
	for ( const key in node ) {
		const child = node[ key ];
		if ( Array.isArray( child ) ) {
			child.forEach( ( item ) => walk( item, visit ) );
		} else if ( child && typeof child === 'object' && key !== 'loc' ) {
			walk( child, visit );
		}
	}
}

/**
 * @param {string} code Bundle source.
 * @return {Map<string, Map<string, string|string[]>>} domain → key → entry.
 */
function extractStrings( code ) {
	const found = new Map();
	const ast = acorn.parse( code, { ecmaVersion: 'latest', sourceType: 'script' } );

	walk( ast, ( node ) => {
		if ( node.type !== 'CallExpression' ) {
			return;
		}
		const spec = FUNCTIONS[ calleeName( node.callee ) ];
		if ( ! spec ) {
			return;
		}
		const msgid = stringValue( node.arguments[ 0 ] );
		if ( ! msgid ) {
			return;
		}
		const context = null === spec.context ? null : stringValue( node.arguments[ spec.context ] );
		if ( null !== spec.context && null === context ) {
			return;
		}
		const domain = node.arguments.length > spec.domain ? stringValue( node.arguments[ spec.domain ] ) : 'default';
		if ( ! domain ) {
			return;
		}

		if ( ! found.has( domain ) ) {
			found.set( domain, new Map() );
		}
		const key = context ? `${ context }\u0004${ msgid }` : msgid;
		found.get( domain ).set( key, context ? [ msgid, context ] : msgid );
	} );

	return found;
}

function phpString( value ) {
	return `'${ value.replace( /\\/g, '\\\\' ).replace( /'/g, "\\'" ) }'`;
}

function toPhp( domains ) {
	const lines = [
		'<?php',
		'// Generated by build-tools/i18n-strings-webpack-plugin.js. Do not edit.',
		'return array(',
	];
	[ ...domains.keys() ].sort().forEach( ( domain ) => {
		lines.push( `\t${ phpString( domain ) } => array(` );
		const entries = domains.get( domain );
		[ ...entries.keys() ].sort().forEach( ( key ) => {
			const entry = entries.get( key );
			lines.push(
				Array.isArray( entry )
					? `\t\tarray( ${ phpString( entry[ 0 ] ) }, ${ phpString( entry[ 1 ] ) } ),`
					: `\t\t${ phpString( entry ) },`
			);
		} );
		lines.push( '\t),' );
	} );
	lines.push( ');', '' );
	return lines.join( '\n' );
}

class I18nStringsPlugin {
	apply( compiler ) {
		compiler.hooks.thisCompilation.tap( PLUGIN_NAME, ( compilation ) => {
			compilation.hooks.processAssets.tap(
				{ name: PLUGIN_NAME, stage: Compilation.PROCESS_ASSETS_STAGE_ANALYSE },
				() => {
					const cache = new Map();
					const stringsIn = ( file ) => {
						if ( ! cache.has( file ) ) {
							const asset = compilation.getAsset( file );
							cache.set( file, asset ? extractStrings( asset.source.source().toString() ) : new Map() );
						}
						return cache.get( file );
					};

					for ( const entrypoint of compilation.entrypoints.values() ) {
						const chunks = new Set();
						for ( const chunk of entrypoint.chunks ) {
							chunks.add( chunk );
							chunk.getAllAsyncChunks().forEach( ( asyncChunk ) => chunks.add( asyncChunk ) );
						}

						const merged = new Map();
						for ( const chunk of chunks ) {
							for ( const file of chunk.files ) {
								if ( ! file.endsWith( '.js' ) ) {
									continue;
								}
								for ( const [ domain, entries ] of stringsIn( file ) ) {
									if ( ! merged.has( domain ) ) {
										merged.set( domain, new Map() );
									}
									entries.forEach( ( entry, key ) => merged.get( domain ).set( key, entry ) );
								}
							}
						}

						const mainFile = [ ...entrypoint.getEntrypointChunk().files ].find( ( file ) => file.endsWith( '.js' ) );
						if ( ! mainFile ) {
							continue;
						}
						compilation.emitAsset(
							mainFile.replace( /\.js$/, '.i18n.php' ),
							new sources.RawSource( toPhp( merged ) )
						);
					}
				}
			);
		} );
	}
}

module.exports = I18nStringsPlugin;
module.exports.extractStrings = extractStrings;
